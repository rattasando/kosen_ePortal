function buildStudents(raw) {
  return raw.map((s) => {
    // ── enrollments ──
    let enrollments = s.enrollments;
    if (!enrollments) {
      const sid    = genStudentId(s.university, s.year);
      const domain = UNI_EMAIL_DOMAIN[s.university] || "kosen.ac.th";
      const first  = {
        university:  s.university  ?? "",
        studentId:   sid,
        univEmail:   `${sid.toLowerCase()}@student.${domain}`,
        faculty:     s.faculty     ?? "",
        department:  s.department  ?? "",
        major:       s.major       ?? "",
        year:        s.year        ?? "",
        advisor:     s.advisor     ?? "",
        project:     s.project     ?? "",
      };
      const jpEnroll = JP_UNIV_ENROLLMENT[s.id];
      enrollments = jpEnroll ? [first, jpEnroll] : [first];
    }

    // ── addresses ──
    let addresses = s.addresses;
    if (!addresses) {
      const isJP  = s.country === "ญี่ปุ่น";
      const jpData = JP_ADDR_MAP[s.address] ?? null;
      const homeTh = JP_STUDENT_HOME_TH[s.id] ?? null;

      const th = isJP
        ? (homeTh ?? { houseNo: "", subdistrict: "", district: "", province: "", postalCode: "" })
        : parseThaAddress(s.address ?? "");
      const jp = isJP && jpData
        ? jpData
        : { postalCode: "", prefecture: "", city: "", streetAddress: "", building: "" };

      addresses = { th, jp };
    }

    return { ...s, enrollments, addresses };
  });
}

