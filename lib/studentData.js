// ── Address parser ────────────────────────────────────────────
function parseThaAddress(addr) {
  if (!addr) return { houseNo: "", subdistrict: "", district: "", province: "", postalCode: "" };
  const postalMatch = addr.match(/(\d{5})\s*$/);
  const postalCode = postalMatch ? postalMatch[1] : "";
  const subdistrictMatch = addr.match(/(?:แขวง|ต\.)([^\s,]+)/);
  const subdistrict = subdistrictMatch ? subdistrictMatch[1] : "";
  const districtMatch = addr.match(/(?:เขต|อ\.)([^\s,]+)/);
  const district = districtMatch ? districtMatch[1] : "";
  let province = "";
  if (addr.includes("กรุงเทพ")) {
    province = "กรุงเทพมหานคร";
  } else {
    const m = addr.match(/จ\.([^\s\d,]+)/);
    if (m) province = m[1];
  }
  const firstKw = addr.search(/\s(?:แขวง|เขต|ต\.|อ\.|จ\.)/);
  const houseNo = firstKw > 0 ? addr.slice(0, firstKw).trim() : addr;
  return { houseNo, subdistrict, district, province, postalCode };
}

