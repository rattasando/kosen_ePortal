// StudentId counter per (prefix+yearCode)
const _counters = {};
function genStudentId(uni, year) {
  const prefix = { "KOSEN-KMUTT": "KM", "KOSEN-KMITL": "KL", "KOSEN-Chulabhorn": "KC" }[uni] || "KS";
  const yearCode = { "1": "68", "2": "67", "3": "66", "4": "65", "5": "64" }[year] || "66";
  const key = prefix + yearCode;
  _counters[key] = (_counters[key] || 0) + 1;
  return `${prefix}${yearCode}${String(_counters[key]).padStart(3, "0")}`;
}

